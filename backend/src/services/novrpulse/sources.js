/** All sources, in registry order. */
export function allSources() {
  return SOURCES;
}

/** Look up a source by id, or undefined. */
export function getSource(id) {
  return SOURCES.find((s) => s.id === id);
}

/** Sources of a given tier. */
export function sourcesByTier(tier) {
  return SOURCES.filter((s) => s.tier === tier);
}

/**
 * Sources that should actually be collected: enabled and feed-backed, either an
 * RSS/Atom feed (`type: 'rss'`) or a WordPress REST endpoint (`type: 'api'`).
 * The engine dispatches to the matching parser.
 */
export function enabledCollectorSources() {
  return SOURCES.filter((s) => s.enabled && (s.type === 'rss' || s.type === 'api') && s.feedUrl);
}

/** Registry stats for quick health checks. */
export function registryStats() {
  const byStatus = {};
  for (const s of SOURCES) byStatus[s.status] = (byStatus[s.status] ?? 0) + 1;
  return { total: SOURCES.length, enabled: enabledCollectorSources().length, byStatus };
}

export default { SOURCES, allSources, getSource, sourcesByTier, enabledCollectorSources, registryStats };
